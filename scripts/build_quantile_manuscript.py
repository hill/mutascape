"""Build manuscript tables and figures from fixed quantile-model results."""

import argparse
import ast
import hashlib
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import kendalltau

from mutascape.benchmarks.validity import reliable_method_pairs
from mutascape.validation.fourier import binary_cube_spectrum

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results/quantile_confirmation_20260923"
PROTEINS = ["DHFR", "eqFP611", "ParB-Noc", "ParD2", "CreiLOV"]
SEEDS = [2026093001, 2026093002, 2026093003]
STYLE = {
    "font.family": "STIX Two Text",
    "mathtext.fontset": "stix",
    "font.size": 9,
    "axes.linewidth": 0.6,
    "pdf.fonttype": 42,
    "svg.fonttype": "none",
    "savefig.facecolor": "white",
}
BLUE, PALE_BLUE = "#167db5", "#c1deeb"
GREEN, PALE_GREEN = "#279d29", "#d2eabf"


def write_table(path, headings, records, widths=None):
    widths = widths or ["1fr"] * len(headings)
    lines = [
        "// Generated by scripts/build_quantile_manuscript.py.",
        "#block[",
        "#set text(size: 8pt)",
        "#table(",
        f"  columns: ({', '.join(widths)}),",
        "  align: (left," + " right," * (len(headings) - 1) + "),",
        "  inset: (x: 4pt, y: 3pt),",
        "  stroke: 0.35pt,",
        "  table.header(" + ", ".join(f"[*{h}*]" for h in headings) + "),",
    ]
    lines.extend("  " + ", ".join(f"[{v}]" for v in row) + "," for row in records)
    path.write_text("\n".join(lines + [")", "]", ""]))


def search_intervals(scores, comparison):
    records = []
    for name in PROTEINS:
        for budget in (48, 96):
            group = scores.loc[
                (scores.protein == name) & (scores.pilot_size == 192) & (scores.budget == budget)
            ]
            measured = (
                group.loc[group.model == "measured"]
                .pivot(index="trial", columns="method", values="regret")
                .sort_index(axis=1)
            )
            generated = (
                group.loc[group.model == "quantile"]
                .groupby(["trial", "method"])
                .regret.mean()
                .unstack()
                .reindex(columns=measured.columns)
            )
            pair_input = group.rename(columns={"model": "arm"}).assign(dataset=name)
            pairs = reliable_method_pairs(pair_input, seed=2026100100, n_bootstrap=2000)
            index = {method: i for i, method in enumerate(measured.columns)}
            first = np.array([index[m] for m in pairs["first"]])
            second = np.array([index[m] for m in pairs["second"]])
            signs = pairs.sign.to_numpy()
            expected = comparison.loc[
                (comparison.protein == name)
                & (comparison.pilot_size == 192)
                & (comparison.budget == budget)
                & (comparison.model == "quantile")
            ].iloc[0]
            assert len(pairs) == expected.scored_pairs
            measured_values, generated_values = measured.to_numpy(), generated.to_numpy()
            means = generated_values.mean(axis=0)
            accuracy = np.mean(np.sign(means[first] - means[second]) == signs)
            assert np.isclose(accuracy, expected.winner_accuracy)
            rng = np.random.default_rng(2026092300 + budget)
            trials = rng.integers(0, len(measured), size=(2000, len(measured)))
            real_boot = measured_values[trials].mean(axis=1)
            generated_boot = generated_values[trials].mean(axis=1)
            taus = [kendalltau(a, b).statistic for a, b in zip(real_boot, generated_boot)]
            agreements = np.mean(
                np.sign(generated_boot[:, first] - generated_boot[:, second]) == signs, axis=1
            )
            for metric, values, point in [
                ("kendall_tau", taus, expected.kendall_tau),
                ("winner_accuracy", agreements, expected.winner_accuracy),
            ]:
                low, high = np.nanquantile(values, [0.025, 0.975])
                records.append(
                    dict(
                        protein=name,
                        budget=budget,
                        metric=metric,
                        point=point,
                        lower=low,
                        upper=high,
                    )
                )
    return pd.DataFrame(records)


def save(figure, destination, name):
    for extension in ("pdf", "svg", "png"):
        figure.savefig(destination / f"{name}.{extension}", bbox_inches="tight", dpi=240)
    plt.close(figure)


def search_figure(intervals, destination):
    with plt.rc_context(STYLE):
        figure, axes = plt.subplots(1, 2, figsize=(7.1, 2.8))
        y = np.arange(len(PROTEINS))
        for axis, metric, title in zip(
            axes,
            ["kendall_tau", "winner_accuracy"],
            ["(a) Method-rank correlation", "(b) Agreement on method winners"],
        ):
            for offset, budget, edge, fill in [
                (-0.17, 48, BLUE, PALE_BLUE),
                (0.17, 96, GREEN, PALE_GREEN),
            ]:
                data = intervals.loc[(intervals.metric == metric) & (intervals.budget == budget)]
                data = data.set_index("protein").loc[PROTEINS]
                axis.barh(
                    y + offset,
                    data.point,
                    0.3,
                    edgecolor=edge,
                    facecolor=fill,
                    linewidth=0.7,
                    label=f"{budget} search queries",
                )
                for yy, row in zip(y + offset, data.itertuples()):
                    axis.plot([row.lower, row.upper], [yy, yy], color=edge, lw=0.7)
                    axis.plot([row.lower, row.upper], [yy, yy], "|", color=edge, markersize=4)
            axis.set_yticks(y, PROTEINS)
            axis.invert_yaxis()
            axis.set_xlim(-0.05 if metric == "kendall_tau" else 0, 1.04)
            axis.set_xticks([0, 0.5, 1])
            axis.set_xlabel("Kendall correlation" if metric == "kendall_tau" else "Pair agreement")
            axis.set_title(title, loc="left", fontsize=10, pad=10)
            axis.spines[["top", "right", "left"]].set_visible(False)
            axis.tick_params(axis="y", length=0)
            axis.tick_params(axis="x", length=3, width=0.6)
        figure.legend(
            *axes[0].get_legend_handles_labels(),
            loc="upper center",
            bbox_to_anchor=(0.5, 1.02),
            ncol=2,
            frameon=False,
        )
        figure.subplots_adjust(left=0.1, right=0.98, top=0.79, bottom=0.18, wspace=0.46)
        save(figure, destination, "search_transfer")


def shape_figure(destination, comparison):
    folder = RESULTS / "CreiLOV"
    frame = pd.read_csv(folder / "genotypes.csv")
    mutations = [ast.literal_eval(m) for m in frame.mutations]
    positions = sorted({p for m in mutations for p in m})
    binary = np.array([sum(1 << i for i, p in enumerate(positions) if p in m) for m in mutations])
    real = frame.fitness.to_numpy()
    generated = np.array([np.load(folder / "p192" / f"quantile_{seed}.npy") for seed in SEEDS])
    test = pd.read_csv(folder / "test.csv").row.to_numpy()
    _, spectrum = binary_cube_spectrum(real, binary, len(positions))
    measured = np.array(list(spectrum.values()))
    spectra = np.array(
        [
            list(binary_cube_spectrum(values, binary, len(positions))[1].values())
            for values in generated
        ]
    )
    expected = comparison.query(
        'protein == "CreiLOV" and pilot_size == 192 and model == "quantile"'
    )
    assert np.isclose(np.median(np.abs(spectra - measured).sum(axis=1)), expected.walsh_l1.iloc[0])
    limits = [
        min(real[test].min(), generated[:, test].min()),
        max(real[test].max(), generated[:, test].max()),
    ]
    bins = np.linspace(*limits, 29)
    centres = (bins[1:] + bins[:-1]) / 2
    observed, _ = np.histogram(real[test], bins=bins, density=True)
    histograms = np.array([np.histogram(v[test], bins=bins, density=True)[0] for v in generated])
    with plt.rc_context(STYLE):
        figure, axes = plt.subplots(1, 2, figsize=(7.1, 2.6))
        med = np.median(histograms, axis=0)
        low, high = histograms.min(axis=0), histograms.max(axis=0)
        axes[0].plot(centres, observed, color="#161616", lw=1, label="Measured")
        axes[0].plot(centres, med, color=BLUE, lw=1, label="Mutascape")
        axes[0].fill_between(centres, low, high, color=PALE_BLUE, alpha=0.8)
        chosen = np.arange(1, len(centres), 4)
        axes[0].errorbar(
            centres[chosen],
            med[chosen],
            yerr=np.vstack([med - low, high - med])[:, chosen],
            fmt="none",
            color=BLUE,
            elinewidth=0.65,
            capsize=2,
        )
        axes[0].set(xlabel="Fitness relative to wild type", ylabel="Density", ylim=(0, None))
        axes[0].set_title("(a) Held-out fitness distribution", loc="left", fontsize=10, pad=10)
        orders = np.arange(1, len(positions) + 1)
        med = np.median(spectra, axis=0)
        low, high = spectra.min(axis=0), spectra.max(axis=0)
        axes[1].bar(
            orders - 0.18, measured, 0.36, facecolor="#e5e5e5", edgecolor="#161616", linewidth=0.65
        )
        axes[1].bar(
            orders + 0.18,
            med,
            0.36,
            facecolor=PALE_BLUE,
            edgecolor=BLUE,
            linewidth=0.65,
            yerr=np.vstack([med - low, high - med]),
            error_kw={"ecolor": BLUE, "elinewidth": 0.65, "capsize": 2},
        )
        axes[1].set(
            xlabel="Interaction order",
            ylabel="Fitness variance fraction",
            xticks=[1, 3, 5, 7, 9, 11, 13, 15],
            ylim=(0, None),
        )
        axes[1].set_title("(b) Projected Walsh spectrum", loc="left", fontsize=10, pad=10)
        for axis in axes:
            axis.spines[["top", "right"]].set_visible(False)
            axis.tick_params(length=3, width=0.6)
        figure.legend(
            *axes[0].get_legend_handles_labels(),
            loc="upper center",
            bbox_to_anchor=(0.5, 1.01),
            ncol=2,
            frameon=False,
        )
        figure.subplots_adjust(left=0.085, right=0.99, top=0.78, bottom=0.2, wspace=0.35)
        save(figure, destination, "creilov_shape_validation")
    return dict(measured_spectrum=measured.tolist(), draw_spectra=spectra.tolist())


def generator_table(manuscript):
    path = RESULTS.parent / "quantile_generator_comparison_20260923/comparison.csv"
    if not path.exists():
        return
    data = pd.read_csv(path)
    models = ["quantile", "additive", "potts", "rmf", "nk_k1", "nk_k2"]
    records = []
    for protein in PROTEINS:
        for budget in (48, 96):
            group = data.loc[(data.protein == protein) & (data.budget == budget)].set_index("model")
            best_tau = group.kendall_tau.round(3).max()
            best_agreement = (group.winner_accuracy * 100).round(1).max()
            row = [protein, budget]
            for model in models:
                r = group.loc[model]
                tau, agreement = f"{r.kendall_tau:.3f}", f"{r.winner_accuracy:.1%}"
                if np.isclose(round(r.kendall_tau, 3), best_tau):
                    tau = f"*{tau}*"
                if np.isclose(round(r.winner_accuracy * 100, 1), best_agreement):
                    agreement = f"*{agreement}*"
                row.append(f"{tau} / {agreement}")
            records.append(row)
    means = data.groupby("model")[["kendall_tau", "winner_accuracy"]].mean()
    best_tau = means.kendall_tau.round(3).max()
    best_agreement = (means.winner_accuracy * 100).round(1).max()
    row = ["Mean", "both"]
    for model in models:
        r = means.loc[model]
        tau, agreement = f"{r.kendall_tau:.3f}", f"{r.winner_accuracy:.1%}"
        if np.isclose(round(r.kendall_tau, 3), best_tau):
            tau = f"*{tau}*"
        if np.isclose(round(r.winner_accuracy * 100, 1), best_agreement):
            agreement = f"*{agreement}*"
        row.append(f"{tau} / {agreement}")
    records.append(row)
    write_table(
        manuscript / "tables/quantile_generators.typ",
        ["Protein", "Queries", "Mutascape", "Additive", "Potts", "RMF", "NK K=1", "NK K=2"],
        records,
        ["0.9fr", "0.55fr", "1.05fr", "1.05fr", "1.05fr", "1.05fr", "1.05fr", "1.05fr"],
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manuscript", type=Path, default=ROOT.parent / "mutascape_manu_v1")
    args = parser.parse_args()
    manuscript = args.manuscript
    generator_table(manuscript)
    comparison = pd.read_csv(RESULTS / "comparison.csv")
    search = pd.read_csv(RESULTS / "search_comparison.csv")
    scores = pd.read_csv(RESULTS / "search_scores.csv")
    records = []
    for name in PROTEINS:
        r = comparison.query('protein == @name and pilot_size == 192 and model == "quantile"').iloc[
            0
        ]
        records.append(
            [
                name,
                f"{r.logistic_original:.3f}",
                f"{r.histogram_original:.3f}",
                f"{r.histogram_sequence:.3f}",
                f"{r.w1:.3f}",
                "n/a" if np.isnan(r.walsh_l1) else f"{r.walsh_l1:.3f}",
            ]
        )
    write_table(
        manuscript / "tables/quantile_fidelity.typ",
        [
            "Protein",
            "Logistic AUC",
            "Boosted AUC",
            "Boosted + sequence",
            "$W_1 / sigma$",
            "Spectrum $D$",
        ],
        records,
        ["1fr", "1fr", "1fr", "1.4fr", "0.8fr", "0.8fr"],
    )
    records = []
    for name in PROTEINS:
        for budget in (48, 96):
            group = search.query("protein == @name and pilot_size == 192 and budget == @budget")
            q = group.query('model == "quantile"').iloc[0]
            fixed = group.query('model == "fixed_other_proteins"').iloc[0]
            records.append(
                [
                    name,
                    budget,
                    f"{q.kendall_tau:.3f}",
                    f"{int(q.correct_pairs)}/{int(q.scored_pairs)}",
                    f"{q.winner_accuracy:.1%}",
                    f"{int(fixed.correct_pairs)}/{int(fixed.scored_pairs)}",
                    f"{fixed.winner_accuracy:.1%}",
                ]
            )
    write_table(
        manuscript / "tables/quantile_search.typ",
        [
            "Protein",
            "Queries",
            "Kendall",
            "Matching pairs",
            "Agreement",
            "Fixed pairs",
            "Fixed agreement",
        ],
        records,
        ["1fr", "0.6fr", "0.7fr", "1fr", "0.8fr", "0.9fr", "1.1fr"],
    )
    sensitivity = []
    for size in (48, 192):
        fidelity = comparison.query('model == "quantile" and pilot_size == @size')
        method = search.query('model == "quantile" and pilot_size == @size')
        fixed = search.query('model == "fixed_other_proteins" and pilot_size == @size')
        sensitivity.append(
            [
                size,
                f"{fidelity.histogram_original.mean():.3f}",
                f"{fidelity.histogram_sequence.mean():.3f}",
                f"{fidelity.w1.mean():.3f}",
                f"{method.kendall_tau.mean():.3f}",
                f"{method.winner_accuracy.mean():.1%}",
                f"{fixed.winner_accuracy.mean():.1%}",
            ]
        )
    write_table(
        manuscript / "tables/quantile_budget.typ",
        [
            "Pilot",
            "Boosted AUC",
            "With sequence",
            "$W_1 / sigma$",
            "Kendall",
            "Agreement",
            "Fixed agreement",
        ],
        sensitivity,
    )
    intervals = search_intervals(scores, search)
    intervals.to_csv(manuscript / "figures/search_transfer_intervals.csv", index=False)
    search_figure(intervals, manuscript / "figures")
    spectra = shape_figure(manuscript / "figures", comparison)
    data = {
        "model": "quantile-pilot-v1",
        "calibration_size": 192,
        "source_sha256": {
            name: hashlib.sha256((RESULTS / name).read_bytes()).hexdigest()
            for name in [
                "comparison.csv",
                "metrics.csv",
                "structure.csv",
                "search_comparison.csv",
                "search_scores.csv",
            ]
        },
        "search_bootstrap": {
            "resamples": 2000,
            "unit": "paired search seed",
            "conditioned_on": "calibration sets, draws, eligible pairs and measured winner signs",
        },
        "creilov": spectra,
    }
    (manuscript / "figures/quantile_provenance.json").write_text(json.dumps(data, indent=2) + "\n")
    print("Built final-model tables and figures.")


if __name__ == "__main__":
    main()
