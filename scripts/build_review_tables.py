"""Build manuscript tables that show every baseline and the fixed-ranking null."""

from pathlib import Path

import numpy as np
import pandas as pd


def build_search_table(manuscript: Path, results: Path) -> None:
    data = pd.read_csv(results / "search_summary.csv")
    nulls = pd.read_csv(results.parent / "review_response_20260923/null_summary.csv")
    rows = []
    for collection, label in [
        ("ssmula", "SSMuLA"),
        ("combingym", "CombinGym"),
        ("graphfla", "GraphFLA"),
    ]:
        for budget in (48, 96, 192, 384):
            subset = data.loc[(data.collection == collection) & (data.budget == budget)].set_index(
                "model"
            )
            fixed = nulls.loc[
                (nulls.collection == collection)
                & (nulls.budget == budget)
                & (nulls.prediction == "Fixed ranking")
                & (nulls.subset == "all"),
                "accuracy",
            ].iloc[0]
            cells = [label, str(budget), str(int(subset.loc["Mutascape", "eligible_pairs"]))]
            best_tau = subset.kendallTau.round(3).max()
            best_accuracy = max(
                subset.pairwiseAccuracy.mul(100).round(1).max(), round(100 * fixed, 1)
            )
            for model in ("Mutascape", "Potts", "RMF", "Additive"):
                record = subset.loc[model]
                suffix = "#super[†]" if collection == "graphfla" and budget == 384 else ""
                tau = f"{record.kendallTau:.3f}"
                accuracy = f"{100 * record.pairwiseAccuracy:.1f}%"
                if np.isclose(round(record.kendallTau, 3), best_tau):
                    tau = f"*{tau}*"
                if np.isclose(round(100 * record.pairwiseAccuracy, 1), best_accuracy):
                    accuracy = f"*{accuracy}*"
                cells.append(f"{tau}{suffix} / {accuracy}")
            fixed_text = f"{100 * fixed:.1f}%"
            if np.isclose(round(100 * fixed, 1), best_accuracy):
                fixed_text = f"*{fixed_text}*"
            cells.append(fixed_text)
            rows.append("  " + ", ".join(f"[{cell}]" for cell in cells) + ",")
    text = (
        """// Generated by scripts/build_review_tables.py.
#block[
#set text(size: 7.3pt)
#table(
  columns: (0.85fr, 0.45fr, 0.6fr, 1.2fr, 1.2fr, 1.2fr, 1.2fr, 0.65fr),
  align: (left, right, right, right, right, right, right, right),
  inset: (x: 3pt, y: 3pt),
  stroke: 0.4pt,
  table.header(
    [*Collection*], [*Queries*], [*Eligible*], [*Singles + pairs*],
    [*Potts*], [*RMF*], [*Additive*], [*Fixed rank*],
  ),
"""
        + "\n".join(rows)
        + "\n)\n]\n"
    )
    (manuscript / "tables/search_results.typ").write_text(text)


def build_control_tables(manuscript: Path, results: Path) -> None:
    """Write complete readout and confirmation comparisons."""
    ablation = pd.read_csv(results / "readout_summary.csv")
    confirmation = pd.read_csv(results / "confirmation_summary.csv")
    specifications = [
        (
            "readout_ablation",
            ablation,
            ["collection", "budget"],
            ["Collection", "Queries", "With readout", "Without readout"],
            ["dms_pairwise_mean", "dms_no_readout_mean"],
        ),
        (
            "confirmation",
            confirmation,
            ["budget"],
            [
                "Queries",
                "Eligible",
                "Mutascape",
                "No readout",
                "Potts",
                "RMF",
                "Additive",
                "Fixed rank",
            ],
            [
                "dms_pairwise_mean",
                "dms_no_readout_mean",
                "potts_low_mean",
                "rmf_high_mean",
                "additive",
                "fixed_ranking",
            ],
        ),
    ]
    for name, frame, keys, headers, models in specifications:
        rows = []
        for key, group in frame.groupby(keys, sort=True):
            key = key if isinstance(key, tuple) else (key,)
            labels = {"ssmula": "SSMuLA", "combingym": "CombinGym", "graphfla": "GraphFLA"}
            cells = [labels.get(str(value), str(value)) for value in key]
            if name == "confirmation":
                cells.append(str(int(group.eligible.iloc[0])))
            group = group.set_index("model")
            for model in models:
                row = group.loc[model]
                cells.append(f"{row.kendall:.3f} / {100 * row.accuracy:.1f}%")
            rows.append("  " + ", ".join(f"[{cell}]" for cell in cells) + ",")
        header = ", ".join(f"[*{h}*]" for h in headers)
        content = (
            f"// Generated by scripts/build_review_tables.py.\n#block[\n#set text(size: 7pt)\n"
            f"#table(columns: {len(headers)}, inset: 3pt, stroke: 0.4pt,\n"
            f"  table.header({header}),\n" + "\n".join(rows) + "\n)\n]\n"
        )
        (manuscript / "tables" / f"{name}.typ").write_text(content)


if __name__ == "__main__":
    build_search_table(Path("../mutascape_manu_v1"), Path("results/preprint_audit_20260923"))
    build_control_tables(Path("../mutascape_manu_v1"), Path("results/review_response_20260923"))
