def distribution_table(study, calibrated, destination):
    """Report full-dataset C2ST beside its matched distribution comparisons."""
    base = pd.DataFrame(study["fidelity_medians"]).query('model == "sigmoid"').set_index("protein")
    extension = pd.DataFrame(calibrated["medians"]).set_index("protein")
    metrics = ["w1", "local_walsh_l1", "auc_sequence"]
    lines = [
        "// Generated by scripts/build_review_manuscript.py.",
        "#block[",
        "#set text(size: 8pt)",
        "#table(",
        "  columns: (0.9fr, 1fr, 0.8fr, 0.8fr, 0.8fr, 1fr, 1fr, 1fr),",
        "  align: (left, right, right, right, right, right, right, right),",
        "  inset: (x: 3pt, y: 3pt),",
        "  stroke: 0.35pt,",
        "  table.header(",
        "    table.cell(rowspan: 2)[*Protein*],",
        "    table.cell(rowspan: 2)[*Genotypes*],",
        "    table.cell(colspan: 3)[*Single-site-only Mutascape*],",
        "    table.cell(colspan: 3)[*Combination-calibrated Mutascape*],",
        "    [*$W_1/sigma_f$*], [*Walsh*], [*AUC*],",
        "    [*$W_1/sigma_f$*], [*Walsh*], [*AUC*],",
        "  ),",
    ]
    for name in [*CONFIRMATION, "Mean"]:
        a, b = (
            (
                base.loc[list(CONFIRMATION), metrics].mean(),
                extension.loc[list(CONFIRMATION), metrics].mean(),
            )
            if name == "Mean"
            else (base.loc[name], extension.loc[name])
        )
        count = "-" if name == "Mean" else f"{int(a.c2st_n):,}"
        if name != "Mean":
            assert a.c2st_n == b.c2st_n == a.distribution_n == b.distribution_n
        cells = []
        for metric in metrics:
            numbers = [f"{a[metric]:.3f}", f"{b[metric]:.3f}"]
            best = min(map(float, numbers))
            cells.extend(f"*{s}*" if float(s) == best else s for s in numbers)
        row = [name, count, *cells[::2], *cells[1::2]]
        lines.append("  " + ", ".join(f"[{value}]" for value in row) + ",")
    (destination / "singles_fidelity.typ").write_text("\n".join([*lines, ")", "]", ""]))
    path = destination / "singles_facts.json"
    facts = json.loads(path.read_text())
    facts.update(
        mutascape_auc_base=f"{base.loc[list(CONFIRMATION), 'auc_base'].mean():.3f}",
        mutascape_auc_sequence=f"{base.loc[list(CONFIRMATION), 'auc_sequence'].mean():.3f}",
        creilov_auc=f"{base.loc['CreiLOV', 'auc_sequence']:.3f}",
    )
    path.write_text(json.dumps(facts, indent=2) + "\n")


def dataset_table(study, destination):
    citations = [
        "papkou_2023",
        "poelwijk_2019",
        "jalal_2020",
        "lite_2020",
        "chen_creilov_2023",
        "wu_2016",
        "johnston_2024",
        "tu_2024",
        "tu_2024",
    ]
    sites = [3, 13, 4, 3, 15, 4, 4, 3, 4]
    inventory = pd.DataFrame(study["inventory"]).set_index("protein")
    rows = [
        [
            f"{name} @{citation}",
            "Model selection" if name in DEVELOPMENT else "Evaluation",
            count,
            int(inventory.loc[name, "singles"]),
            f"{int(inventory.loc[name, 'measured']):,}",
        ]
        for name, citation, count in zip((*DEVELOPMENT, *CONFIRMATION), citations, sites)
    ]
    original.write_table(
        destination / "singles_datasets.typ",
        ["Protein", "Use", "Sites", "Single-site variants", "Experimental genotypes"],
        rows,
        ["1.4fr", "1fr", "0.5fr", "1fr", "1.1fr"],
    )


def search_assets(study, destination):
    """Reproduce the ten-repeat study currently reported on manuscript main."""
    results = pd.DataFrame(study["dms_search"])
    models = ["sigmoid", "additive", "linear", "main_singles", "fixed_ranking"]
    rows = []
    for budget in (48, 96):
        for name in [*CONFIRMATION, "Mean"]:
            subset = results.loc[(results.budget == budget) & results.protein.isin(CONFIRMATION)]
            group = (
                subset.groupby("model")[["kendall_tau", "winner_accuracy"]].mean()
                if name == "Mean"
                else subset.loc[subset.protein == name].set_index("model")
            )
            tau = [f"{group.loc[m, 'kendall_tau']:.3f}" for m in models]
            agreement = [f"{100 * group.loc[m, 'winner_accuracy']:.1f}" for m in models]
            best_tau = max(map(float, tau))
            best_pct = max((float(v) for v in agreement if v != "nan"), default=np.nan)
            cells = []
            for t, a in zip(tau, agreement):
                t = f"*{t}*" if float(t) == best_tau else t
                a = "-" if a == "nan" else f"*{a}%*" if float(a) == best_pct else f"{a}%"
                cells.append(f"{t} / {a}")
            rows.append([f"{name}, {budget}", *cells])
    original.write_table(
        destination / "tables/singles_generators.typ",
        [
            "Protein, evaluations",
            "Single-site-only#linebreak()Mutascape",
            "Mutascape#linebreak()additive",
            "Mutascape#linebreak()linear",
            "Mutascape#linebreak()empirical-range",
            "Fixed rank",
        ],
        rows,
        ["1.05fr", *["1fr"] * 5],
    )
    intervals = original.search_intervals(study)
    counts = results.loc[
        results.model == "sigmoid", ["protein", "budget", "correct_pairs", "scored_pairs"]
    ]
    intervals = intervals.merge(counts, on=["protein", "budget"], validate="many_to_one")
    intervals = intervals.rename(
        columns={"correct_pairs": "matching_pairs", "scored_pairs": "eligible_pairs"}
    )
    original.search_figure(intervals, destination / "figures")
    intervals.to_csv(destination / "figures/search_transfer_intervals.csv", index=False)


def creilov_figure(destination):
    frame, design, _ = data("CreiLOV")
    real = frame.fitness.to_numpy()
    rows = np.load(OUT / "CreiLOV/distribution_rows.npy")
    samples = {
        "Mutascape": np.array(
            [
                np.load(original.RESULTS / "CreiLOV" / f"fitness_sigmoid_{seed}.npy")
                for seed in SEEDS
            ]
        ),
        "Combination-calibrated Mutascape": np.array(
            [np.load(OUT / "CreiLOV" / f"evaluation_{seed}.npy") for seed in SEEDS]
        ),
    }
    spectra = {
        name: np.array([local_geometry(v, design["cubes"])[0] for v in values])
        for name, values in samples.items()
    }
    experimental = local_geometry(real, design["cubes"])[0]
    bins = np.linspace(
        min(real[rows].min(), *[v[:, rows].min() for v in samples.values()]),
        max(real[rows].max(), *[v[:, rows].max() for v in samples.values()]),
        29,
    )
    centres = (bins[1:] + bins[:-1]) / 2
    observed = np.histogram(real[rows], bins=bins, density=True)[0]
    histograms = {
        name: np.array([np.histogram(v[rows], bins=bins, density=True)[0] for v in values])
        for name, values in samples.items()
    }
    np.testing.assert_allclose(np.sum(observed * np.diff(bins)), 1)
    for values in histograms.values():
        np.testing.assert_allclose(np.sum(values * np.diff(bins), axis=1), 1)
    with plt.rc_context(STYLE):
        fig, axes = plt.subplots(1, 2, figsize=(7.1, 2.75))
        spectrum_axis, distribution_axis = axes
        distribution_axis.stairs(observed, bins, color="#111111", lw=1, label="Experimental")
        x = np.arange(3)
        spectrum_axis.bar(
            x - 0.23, experimental, width=0.2, color="#e0e0e0", edgecolor="#111111", lw=0.8
        )
        for offset, (name, edge, fill) in enumerate(
            [
                ("Mutascape", BLUE, PALE_BLUE),
                ("Combination-calibrated Mutascape", GREEN, PALE_GREEN),
            ]
        ):
            hist = histograms[name]
            mid, lo, hi = np.median(hist, axis=0), hist.min(axis=0), hist.max(axis=0)
            label = "Single-site-only Mutascape" if name == "Mutascape" else name
            distribution_axis.stairs(mid, bins, color=edge, lw=1, label=label)
            distribution_axis.stairs(hi, bins, baseline=lo, fill=True, color=fill, alpha=0.65)
            distribution_axis.errorbar(
                centres,
                mid,
                yerr=[mid - lo, hi - mid],
                fmt="none",
                color=edge,
                lw=0.55,
                capsize=1.5,
            )
            spec = spectra[name]
            mid = np.median(spec, axis=0)
            spectrum_axis.bar(
                x + offset * 0.23,
                mid,
                width=0.2,
                color=fill,
                edgecolor=edge,
                lw=0.8,
                yerr=[mid - spec.min(axis=0), spec.max(axis=0) - mid],
                error_kw={"ecolor": edge, "elinewidth": 0.65, "capsize": 2},
            )
        distribution_axis.set(
            title="(b) Fluorescence distributions",
            xlabel="Log fluorescence relative to WT",
            ylabel="Density",
            ylim=(0, None),
        )
        distribution_axis.legend(frameon=False, fontsize=7.5)
        spectrum_axis.set(
            title="(a) Local Walsh spectra",
            xlabel="Interaction order",
            ylabel="Fraction of local variance",
            ylim=(0, 1.05),
        )
        spectrum_axis.set_xticks(x, ["1", "2", "3"])
        for ax, title in zip(axes, ["(a) Local Walsh spectra", "(b) Fluorescence distributions"]):
            ax.set_title("")
            ax.set_title(title, loc="left", fontsize=10)
            ax.spines[["top", "right"]].set_visible(False)
        fig.subplots_adjust(wspace=0.3, bottom=0.2, top=0.87)
        original.save(fig, destination, "creilov_shape_validation")
    payload = dict(
        distribution_n=len(rows),
        calibration_n=96,
        seeds=SEEDS,
        distribution_rows_sha256=digest(OUT / "CreiLOV/distribution_rows.npy"),
        experimental_spectrum=experimental.tolist(),
        spectra={k: v.tolist() for k, v in spectra.items()},
        bin_edges=bins.tolist(),
        experimental_histogram=observed.tolist(),
        histograms={k: v.tolist() for k, v in histograms.items()},
    )
    (destination / "creilov_shape_data.json").write_text(json.dumps(payload, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manuscript", type=Path, default=original.ROOT.parent / "mutascape_manu_v1"
    )
    parser.add_argument("--tables-only", action="store_true")
    args = parser.parse_args()
    study = json.loads((FULL_C2ST / "singles-full-evaluation.json").read_text())
    calibrated = json.loads((FULL_C2ST / "calibration96-full-evaluation.json").read_text())
    original.tables(study, calibrated, args.manuscript / "tables")
    dataset_table(study, args.manuscript / "tables")
    distribution_table(study, calibrated, args.manuscript / "tables")
    if not args.tables_only:
        search_assets(study, args.manuscript)
        creilov_figure(args.manuscript / "figures")
    for path in (args.manuscript / "tables").glob("singles_*.typ"):
        source = (
            path.read_text()
            .replace(
                "// Generated by scripts/build_singles_manuscript.py.",
                "// Generated by scripts/build_review_manuscript.py.",
            )
            .replace("#set text(size: 8pt)", "#set text(size: 8pt)\n#set par(justify: false)")
        )
        path.write_text(source)
    print("Rebuilt review tables from saved experiments.")


if __name__ == "__main__":
    main()
