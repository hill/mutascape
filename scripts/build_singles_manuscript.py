def write_table(path, headings, records, widths=None, groups=None):
    widths = widths or ["1fr"] * len(headings)
    lines = [
        "// Generated by scripts/build_singles_manuscript.py.",
        "#block[",
        "#set text(size: 8pt)",
        "#table(",
        f"  columns: ({', '.join(widths)}),",
        "  align: (left," + " right," * (len(headings) - 1) + "),",
        "  inset: (x: 3pt, y: 3pt),",
        "  stroke: 0.35pt,",
    ]
    if groups:
        cells = [f"table.cell(rowspan: 2)[*{headings[0]}*]"]
        cells += [f"table.cell(colspan: 3)[*{label}*]" for label in groups]
        cells += [f"[*{h}*]" for h in headings[1:]]
    else:
        cells = [f"[*{h}*]" for h in headings]
    lines.append("  table.header(" + ", ".join(cells) + "),")
    lines.extend("  " + ", ".join(f"[{v}]" for v in row) + "," for row in records)
    path.write_text("\n".join(lines + [")", "]", ""]))


def save(figure, destination, name):
    for extension in ("pdf", "svg", "png"):
        path = destination / f"{name}.{extension}"
        figure.savefig(path, bbox_inches="tight", dpi=240)
        if extension == "svg":
            path.write_text(
                "\n".join(line.rstrip() for line in path.read_text().splitlines()) + "\n"
            )
    plt.close(figure)


def tables(study, pilot, destination):
    destination.mkdir(parents=True, exist_ok=True)
    inventory = pd.DataFrame(study["inventory"]).set_index("protein")
    citations = dict(
        DHFR="papkou_2023",
        eqFP611="poelwijk_2019",
        **{"ParB-Noc": "jalal_2020"},
        ParD2="lite_2020",
        CreiLOV="chen_creilov_2023",
        GB1="wu_2016",
        TrpB4="johnston_2024",
        T7="tu_2024",
        TEV="tu_2024",
    )
    sites = dict(
        DHFR=3, eqFP611=13, **{"ParB-Noc": 4}, ParD2=3, CreiLOV=15, GB1=4, TrpB4=4, T7=3, TEV=4
    )
    records = []
    for name in (*DEVELOPMENT, *CONFIRMATION):
        row = inventory.loc[name]
        records.append(
            [
                f"{name} @{citations[name]}",
                "Develop." if name in DEVELOPMENT else "Confirm.",
                sites[name],
                int(row.singles),
                f"{int(row.declared):,}",
                f"{int(row.measured):,}",
            ]
        )
    write_table(
        destination / "singles_datasets.typ",
        ["Protein", "Use", "Sites", "Singles", "Declared", "Measured"],
        records,
        ["1.5fr", "0.9fr", "0.6fr", "0.7fr", "1fr", "1fr"],
    )
    base = pd.DataFrame(study["fidelity_medians"]).query('model == "sigmoid"').set_index("protein")
    extension = pd.DataFrame(pilot["medians"]).set_index("protein")
    metrics = ["w1", "local_walsh_l1", "auc_sequence"]
    records = []
    for name in [*CONFIRMATION, "Mean"]:
        a = (
            base.loc[list(CONFIRMATION), metrics].mean()
            if name == "Mean"
            else base.loc[name, metrics]
        )
        b = (
            extension.loc[list(CONFIRMATION), metrics].mean()
            if name == "Mean"
            else extension.loc[name, metrics]
        )
        cells = []
        for metric in metrics:
            numbers = [f"{a[metric]:.3f}", f"{b[metric]:.3f}"]
            best = min(map(float, numbers))
            cells += [f"*{s}*" if float(s) == best else s for s in numbers]
        records.append([name, *cells[::2], *cells[1::2]])
    write_table(
        destination / "singles_fidelity.typ",
        [
            "Protein",
            "$W_1/sigma_f$",
            "Walsh",
            "AUC",
            "$W_1/sigma_f$",
            "Walsh",
            "AUC",
        ],
        records,
        ["1.15fr", *["1fr"] * 6],
        groups=["Mutascape", "Combination-calibrated Mutascape"],
    )
    warm = pd.DataFrame(study["dms_search"])
    models = ["sigmoid", "additive", "linear", "main_singles", "fixed_ranking"]
    records = []
    for budget in (48, 96):
        for name in [*CONFIRMATION, "Mean"]:
            data = warm.loc[warm.budget == budget]
            group = (
                data.groupby("model")[["kendall_tau", "winner_accuracy"]].mean()
                if name == "Mean"
                else data.loc[data.protein == name].set_index("model")
            )
            tau = [f"{group.loc[m, 'kendall_tau']:.3f}" for m in models]
            pct = [f"{100 * group.loc[m, 'winner_accuracy']:.1f}" for m in models]
            best_tau = max(map(float, tau))
            best_pct = max((float(s) for s in pct if s != "nan"), default=np.nan)
            cells = []
            for t, p in zip(tau, pct):
                t = f"*{t}*" if float(t) == best_tau else t
                p = "-" if p == "nan" else f"*{p}%*" if float(p) == best_pct else f"{p}%"
                cells.append(f"{t} / {p}")
            records.append([f"{name}, {budget}", *cells])
    write_table(
        destination / "singles_generators.typ",
        [
            "Protein, queries",
            "Mutascape",
            "Additive",
            "Linear + pairs",
            "Empirical range",
            "Fixed rank",
        ],
        records,
        ["1.05fr", *["1fr"] * 5],
    )
    facts = {
        "pilot_auc": f"{extension.loc[list(CONFIRMATION), 'auc_sequence'].mean():.3f}",
        "pilot_w1": f"{extension.loc[list(CONFIRMATION), 'w1'].mean():.3f}",
        "pilot_improved": int(
            (
                extension.loc[list(CONFIRMATION), "auc_sequence"]
                < base.loc[list(CONFIRMATION), "auc_sequence"]
            ).sum()
        ),
        "creilov_pilot_auc": f"{extension.loc['CreiLOV', 'auc_sequence']:.3f}",
    }
    (destination / "singles_facts.json").write_text(json.dumps(facts, indent=2) + "\n")


def search_intervals(study):
    summary = pd.DataFrame(study["dms_search"]).query('model == "sigmoid"')
    records = []
    for name in CONFIRMATION:
        measured = pd.read_csv(RESULTS / name / "warm_measured_0.csv")
        generated = pd.concat(
            [pd.read_csv(RESULTS / name / f"warm_sigmoid_{s}.csv") for s in SEEDS]
        )
        for budget in (48, 96):
            real = measured.query("budget == @budget").pivot(
                index="trial", columns="method", values="regret"
            )
            synthetic = (
                generated.query("budget == @budget")
                .groupby(["trial", "method"])
                .regret.mean()
                .unstack()
                .reindex(columns=real.columns)
            )
            pairs = reliable_method_pairs(
                measured.query("budget == @budget")
                .rename(columns={"model": "arm"})
                .assign(dataset=name),
                seed=2026092300,
                n_bootstrap=2000,
            )
            expected = summary.loc[(summary.protein == name) & (summary.budget == budget)].iloc[0]
            assert len(pairs) == expected.scored_pairs
            assert np.isclose(
                kendalltau(real.mean().round(12), synthetic.mean().round(12)).statistic,
                expected.kendall_tau,
            )
            indices = {m: i for i, m in enumerate(real.columns)}
            first = np.array([indices[m] for m in pairs["first"]], dtype=int)
            second = np.array([indices[m] for m in pairs["second"]], dtype=int)
            rng = np.random.default_rng(2026092300 + budget)
            sampled = rng.integers(0, len(real), size=(2000, len(real)))
            a, b = real.to_numpy()[sampled].mean(axis=1), synthetic.to_numpy()[sampled].mean(axis=1)
            tau = [kendalltau(x.round(12), y.round(12)).statistic for x, y in zip(a, b)]
            if len(pairs):
                agreement = np.mean(
                    np.sign(b[:, first] - b[:, second]) == pairs.sign.to_numpy(), axis=1
                )
                means = synthetic.mean().to_numpy()
                assert np.isclose(
                    np.mean(np.sign(means[first] - means[second]) == pairs.sign),
                    expected.winner_accuracy,
                )
            else:
                agreement = None
            for metric, values in [("kendall_tau", tau), ("winner_accuracy", agreement)]:
                low, high = (
                    np.nanquantile(values, [0.025, 0.975])
                    if values is not None
                    else (np.nan, np.nan)
                )
                records.append(
                    dict(
                        protein=name,
                        budget=budget,
                        metric=metric,
                        point=expected[metric],
                        lower=low,
                        upper=high,
                    )
                )
    return pd.DataFrame(records)


def search_figure(intervals, destination):
    with plt.rc_context(STYLE):
        fig, axes = plt.subplots(1, 2, figsize=(7.1, 2.75))
        for ax, metric, title in zip(
            axes,
            ("kendall_tau", "winner_accuracy"),
            ("(a) Method-rank correlation", "(b) Agreement on method winners"),
        ):
            for offset, budget, edge, fill in [
                (-0.17, 48, BLUE, PALE_BLUE),
                (0.17, 96, GREEN, PALE_GREEN),
            ]:
                data = (
                    intervals.loc[(intervals.metric == metric) & (intervals.budget == budget)]
                    .set_index("protein")
                    .loc[list(CONFIRMATION)]
                )
                for index, row in enumerate(data.itertuples()):
                    y = index + offset
                    if not np.isfinite(row.point):
                        ax.text(0.05, y, "no eligible pairs", va="center", fontsize=7, color=BLUE)
                        continue
                    ax.barh(
                        y,
                        row.point,
                        height=0.28,
                        facecolor=fill,
                        edgecolor=edge,
                        linewidth=0.85,
                        label=f"{budget} queries" if index == 0 else None,
                    )
                    ax.plot([row.lower, row.upper], [y, y], color=edge, lw=0.8)
                    ax.plot([row.lower, row.lower], [y - 0.055, y + 0.055], color=edge, lw=0.8)
                    ax.plot([row.upper, row.upper], [y - 0.055, y + 0.055], color=edge, lw=0.8)
            ax.set_yticks(range(len(CONFIRMATION)), CONFIRMATION)
            ax.invert_yaxis()
            ax.set_title(title, loc="left", fontsize=10)
            ax.spines[["top", "right", "left"]].set_visible(False)
            ax.tick_params(axis="y", length=0)
            ax.axvline(0, color="#777777", lw=0.5)
            ax.set_xlim((-0.85, 1.02) if metric == "kendall_tau" else (0, 1.04))
            ax.set_xlabel(
                "Kendall correlation" if metric == "kendall_tau" else "Fraction of eligible pairs"
            )
        handles, labels = axes[0].get_legend_handles_labels()
        fig.legend(
            handles,
            labels,
            frameon=False,
            loc="upper center",
            bbox_to_anchor=(0.5, 1.07),
            ncol=2,
            fontsize=8,
        )
        fig.subplots_adjust(wspace=0.34, bottom=0.2, top=0.87)
        save(fig, destination, "search_transfer")


def creilov_figure(destination):
    frame = pd.read_pickle(RESULTS / "CreiLOV/frame.pkl")
    design = np.load(RESULTS / "CreiLOV/design.npz")
    real = frame.fitness.to_numpy()
    samples = {
        "Mutascape": np.array(
            [np.load(RESULTS / "CreiLOV" / f"fitness_sigmoid_{s}.npy") for s in SEEDS]
        ),
        "Combination-calibrated Mutascape": np.array(
            [np.load(PILOT / "CreiLOV" / f"evaluation_{s}.npy") for s in SEEDS]
        ),
    }
    test, cubes = design["test"], design["cubes"]
    spectra = {
        label: np.array([local_geometry(v, cubes)[0] for v in values])
        for label, values in samples.items()
    }
    measured = local_geometry(real, cubes)[0]
    lo = min(real[test].min(), *[v[:, test].min() for v in samples.values()])
    hi = max(real[test].max(), *[v[:, test].max() for v in samples.values()])
    bins = np.linspace(lo, hi, 29)
    centres = (bins[1:] + bins[:-1]) / 2
    observed = np.histogram(real[test], bins=bins, density=True)[0]
    histograms = {
        label: np.array([np.histogram(v[test], bins=bins, density=True)[0] for v in values])
        for label, values in samples.items()
    }
    with plt.rc_context(STYLE):
        fig, axes = plt.subplots(1, 2, figsize=(7.1, 2.75))
        axes[0].plot(centres, observed, color="#111111", lw=1, label="Measured")
        x = np.arange(3)
        axes[1].bar(
            x - 0.23,
            measured,
            width=0.2,
            color="#e0e0e0",
            edgecolor="#111111",
            lw=0.8,
            label="Measured",
        )
        for offset, (label, edge, fill) in enumerate(
            [
                ("Mutascape", BLUE, PALE_BLUE),
                ("Combination-calibrated Mutascape", GREEN, PALE_GREEN),
            ]
        ):
            hist = histograms[label]
            mid, lower, upper = np.median(hist, axis=0), hist.min(axis=0), hist.max(axis=0)
            axes[0].plot(centres, mid, color=edge, lw=1, label=label)
            axes[0].fill_between(centres, lower, upper, color=fill, alpha=0.65)
            axes[0].errorbar(
                centres,
                mid,
                yerr=[mid - lower, upper - mid],
                fmt="none",
                color=edge,
                lw=0.55,
                capsize=1.5,
            )
            spec = spectra[label]
            mid = np.median(spec, axis=0)
            axes[1].bar(
                x + offset * 0.23,
                mid,
                width=0.2,
                color=fill,
                edgecolor=edge,
                lw=0.8,
                label=label,
                yerr=[mid - spec.min(axis=0), spec.max(axis=0) - mid],
                error_kw={"ecolor": edge, "elinewidth": 0.65, "capsize": 2},
            )
        axes[0].set_title("(a) Fitness distributions", loc="left", fontsize=10)
        axes[0].set_xlabel("Log fluorescence relative to WT")
        axes[0].set_ylabel("Density")
        axes[0].set_ylim(bottom=0)
        axes[0].legend(frameon=False, fontsize=7.5)
        axes[1].set_title("(b) Local Walsh spectra", loc="left", fontsize=10)
        axes[1].set_xticks(x, ["1", "2", "3"])
        axes[1].set_xlabel("Interaction order")
        axes[1].set_ylabel("Fraction of local variance")
        axes[1].set_ylim(0, 1.05)
        for ax in axes:
            ax.spines[["top", "right"]].set_visible(False)
        fig.subplots_adjust(wspace=0.3, bottom=0.2, top=0.87)
        save(fig, destination, "creilov_shape_validation")
    payload = dict(
        measured_spectrum=measured.tolist(),
        spectra={k: v.tolist() for k, v in spectra.items()},
        bin_edges=bins.tolist(),
        measured_histogram=observed.tolist(),
        histograms={k: v.tolist() for k, v in histograms.items()},
    )
    (destination / "creilov_shape_data.json").write_text(json.dumps(payload, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manuscript", type=Path, default=ROOT.parent / "mutascape_manu_v1")
    args = parser.parse_args()
    study = json.loads((VALIDATION / "singles-only-research-v1.json").read_text())
    pilot = json.loads((VALIDATION / "singles-pilot-extension-v1.json").read_text())
    tables(study, pilot, args.manuscript / "tables")
    intervals = search_intervals(study)
    intervals.to_csv(args.manuscript / "figures/singles_search_intervals.csv", index=False)
    search_figure(intervals, args.manuscript / "figures")
    creilov_figure(args.manuscript / "figures")
    print("Rebuilt singles-only manuscript tables and result figures.")


if __name__ == "__main__":
    main()
